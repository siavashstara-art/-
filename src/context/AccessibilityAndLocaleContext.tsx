export interface AccessibilityState {
  locale: SupportedLocale;
  adhdFocusMode: boolean;
  motorLargeTargets: boolean;
  visualHighContrast: boolean;
  fontScale: 'normal' | 'large' | 'xlarge';
  hearingVisualCaptions: boolean;
  lastCaptionBanner: string | null;
  visualFlashActive: boolean;
}

interface AccessibilityContextValue extends AccessibilityState {
  t: UITranslations;
  localeMeta: LocaleMeta;
  setLocale: (loc: SupportedLocale) => void;
  toggleAdhdFocusMode: () => void;
  toggleMotorLargeTargets: () => void;
  toggleVisualHighContrast: () => void;
  cycleFontScale: () => void;
  toggleHearingVisualCaptions: () => void;
  announceAndCaption: (text: string) => void;
}

const AccessibilityContext = createContext<AccessibilityContextValue | undefined>(
  undefined
);

const STORAGE_KEY = 'foroshyar_ablecity_a11y_locale_v4';

export const AccessibilityProvider: React.FC<{ children: React.ReactNode }> = ({
  children,
}) => {
  const [state, setState] = useState<AccessibilityState>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        return {
          locale: SUPPORTED_LOCALES[parsed.locale as SupportedLocale]
            ? parsed.locale
            : 'fa',
          adhdFocusMode: Boolean(parsed.adhdFocusMode),
          motorLargeTargets: Boolean(parsed.motorLargeTargets),
          visualHighContrast: Boolean(parsed.visualHighContrast),
          fontScale: parsed.fontScale || 'normal',
          hearingVisualCaptions: Boolean(parsed.hearingVisualCaptions),
          lastCaptionBanner: null,
          visualFlashActive: false,
        };
      }
    } catch {
      // ignore
    }
    return {
      locale: 'fa',
      adhdFocusMode: false,
      motorLargeTargets: false,
      visualHighContrast: false,
      fontScale: 'normal',
      hearingVisualCaptions: false,
      lastCaptionBanner: null,
      visualFlashActive: false,
    };
  });

  useEffect(() => {
    try {
      const { lastCaptionBanner: _, visualFlashActive: __, ...persisted } = state;
      localStorage.setItem(STORAGE_KEY, JSON.stringify(persisted));
    } catch {
      // ignore
    }

    const meta = SUPPORTED_LOCALES[state.locale] || SUPPORTED_LOCALES.fa;
    document.documentElement.lang = meta.code;
    document.documentElement.dir = meta.dir;

    document.documentElement.classList.toggle('a11y-high-contrast', state.visualHighContrast);
    document.documentElement.classList.toggle('a11y-motor-large', state.motorLargeTargets);
    document.documentElement.classList.toggle('a11y-adhd-focus', state.adhdFocusMode);
    document.documentElement.classList.remove('a11y-font-large', 'a11y-font-xlarge');
    if (state.fontScale === 'large') {
      document.documentElement.classList.add('a11y-font-large');
    } else if (state.fontScale === 'xlarge') {
      document.documentElement.classList.add('a11y-font-xlarge');
    }
  }, [state]);

  const announceAndCaption = (text: string) => {
    setState((prev) => ({
      ...prev,
      lastCaptionBanner: text,
      visualFlashActive: prev.hearingVisualCaptions,
    }));

    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      window.speechSynthesis.cancel();
      const u = new SpeechSynthesisUtterance(text);
      u.lang = SUPPORTED_LOCALES[state.locale]?.speechLang || 'fa-IR';
      window.speechSynthesis.speak(u);
    }

    setTimeout(() => {
      setState((prev) => ({ ...prev, visualFlashActive: false }));
    }, 900);
  };

  const value: AccessibilityContextValue = {
    ...state,
    t: UI_TRANSLATIONS[state.locale] || UI_TRANSLATIONS.fa,
    localeMeta: SUPPORTED_LOCALES[state.locale] || SUPPORTED_LOCALES.fa,
    setLocale: (locale) => setState((prev) => ({ ...prev, locale })),
    toggleAdhdFocusMode: () =>
      setState((prev) => ({ ...prev, adhdFocusMode: !prev.adhdFocusMode })),
    toggleMotorLargeTargets: () =>
      setState((prev) => ({ ...prev, motorLargeTargets: !prev.motorLargeTargets })),
    toggleVisualHighContrast: () =>
      setState((prev) => ({ ...prev, visualHighContrast: !prev.visualHighContrast })),
    cycleFontScale: () =>
      setState((prev) => ({
        ...prev,
        fontScale:
          prev.fontScale === 'normal'
            ? 'large'
            : prev.fontScale === 'large'
            ? 'xlarge'
            : 'normal',
      })),
    toggleHearingVisualCaptions: () =>
      setState((prev) => ({
        ...prev,
        hearingVisualCaptions: !prev.hearingVisualCaptions,
      })),
    announceAndCaption,
  };

  return (
    <AccessibilityContext.Provider value={value}>
      {children}
    </AccessibilityContext.Provider>
  );
};

export function useAccessibility() {
  const ctx = useContext(AccessibilityContext);
  if (!ctx) {
    throw new Error('useAccessibility must be used inside AccessibilityProvider');
  }
  return ctx;
}
